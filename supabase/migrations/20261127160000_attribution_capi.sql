-- ---------- first-touch protection ----------
create or replace function public.esy_protect_first_touch()
returns trigger language plpgsql set search_path = '' as $$
declare
  earlier boolean := false;
begin
  if coalesce(current_setting('esy.attr_override', true), '') = 'on' then
    return new;
  end if;
  if old.first_touch is not null and new.first_touch is distinct from old.first_touch then
    begin
      earlier := new.first_touch is not null
        and (new.first_touch->>'at')::timestamptz < (old.first_touch->>'at')::timestamptz;
    exception when others then
      earlier := false;
    end;
    if not coalesce(earlier, false) then
      new.first_touch := old.first_touch;
    end if;
  end if;
  if not coalesce(earlier, false) then
    if old.utm_source is not null or old.utm_medium is not null or old.utm_campaign is not null
       or old.utm_content is not null or old.utm_term is not null then
      new.utm_source := old.utm_source;
      new.utm_medium := old.utm_medium;
      new.utm_campaign := old.utm_campaign;
      new.utm_content := old.utm_content;
      new.utm_term := old.utm_term;
    end if;
    if old.lead_source is not null then new.lead_source := old.lead_source; end if;
    if old.submitted_at is not null then new.submitted_at := old.submitted_at; end if;
  end if;
  return new;
end;
$$;
drop trigger if exists "05_protect_first_touch" on public.contacts;
create trigger "05_protect_first_touch"
  before update on public.contacts
  for each row execute function public.esy_protect_first_touch();

