-- ---------- deal stage -> Meta CAPI (via meta-capi edge function) ----------
-- meta-capi re-reads the deal from the DB and only sends when the deal really is in a mapped
-- stage; event_id 'deal.<id>.<stage>' makes each stage event go out once.
create or replace function public.esy_deal_stage_capi()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.stage in ('call-booked', 'proposal-sent', 'won')
     and (tg_op = 'INSERT' or new.stage is distinct from old.stage) then
    begin
      perform net.http_post(
        url := 'https://jgujrubjdittbgjwzhwn.supabase.co/functions/v1/meta-capi',
        headers := jsonb_build_object('Content-Type', 'application/json'),
        body := jsonb_build_object('deal_id', new.id, 'stage', new.stage),
        timeout_milliseconds := 5000
      );
    exception when others then
      raise warning 'esy_deal_stage_capi failed: %', sqlerrm;
    end;
  end if;
  return null;
end;
$$;
revoke all on function public.esy_deal_stage_capi() from public, anon, authenticated;
drop trigger if exists "91_deal_stage_capi" on public.deals;
create trigger "91_deal_stage_capi"
  after insert or update of stage on public.deals
  for each row execute function public.esy_deal_stage_capi();

