-- Lead attribution (first touch / last touch) + Meta Conversions API plumbing.
-- 2026-11-27, Ricky (Marketing). Asked by Ernest 15:09 IST via Ava.
--
-- 1. contacts: first_touch / last_touch jsonb + flat Meta match keys.
--    first_touch is write-once: a trigger keeps the old value unless the new touch is
--    strictly EARLIER (a backdated Meta instant-form import). The legacy utm_* columns and
--    lead_source mirror first touch and are protected by the same trigger, so no code path
--    (old or new lead-intake, Calendly, UI) can overwrite them again (Thierry bug, contact 58).
-- 2. lead_touches: one row per touch (website submit, Meta instant form, Calendly booking).
-- 3. meta_ad_lookup: id -> name map for campaigns / ad sets / ads.
-- 4. capi_events: log of every Conversions API send (no raw PII; status, ids, response).
-- 5. deals trigger: stage call-booked / proposal-sent / won -> pg_net POST to meta-capi.

alter table public.contacts
  add column if not exists first_touch jsonb,
  add column if not exists last_touch jsonb,
  add column if not exists meta_lead_id text,
  add column if not exists fbc text,
  add column if not exists fbp text,
  add column if not exists submitted_at timestamptz;

comment on column public.contacts.first_touch is 'First touch attribution (write-once; replaced only by an earlier touch). Keys: at, channel, source, campaign_id/name, adset_id/name, ad_id/name, form_id/name, page, page_url, utm_*, fbclid, fbc, fbp, platform, meta_lead_id, event_id.';
comment on column public.contacts.last_touch is 'Latest touch attribution, same keys as first_touch. Overwritten on every touch.';
comment on column public.contacts.submitted_at is 'When the lead first submitted (Meta created_time or browser submit time), not the import time.';

create table if not exists public.lead_touches (
  id bigint generated by default as identity primary key,
  contact_id bigint not null references public.contacts(id) on delete cascade,
  touch_at timestamptz not null,
  recorded_at timestamptz not null default now(),
  channel text not null,               -- website | meta_instant_form | calendly | backfill
  meta_lead_id text unique,            -- Meta leadgen id (instant forms) -> dedup of repeated pulls
  event_id text,                       -- browser pixel / CAPI shared event id (website)
  attribution jsonb not null default '{}'::jsonb
);
create index if not exists lead_touches_contact_idx on public.lead_touches(contact_id, touch_at);

create table if not exists public.meta_ad_lookup (
  object_id text primary key,
  level text not null check (level in ('campaign', 'adset', 'ad', 'form')),
  name text not null,
  campaign_id text,
  adset_id text,
  updated_at timestamptz not null default now()
);

create table if not exists public.capi_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  contact_id bigint references public.contacts(id) on delete set null,
  deal_id bigint,
  event_name text not null,
  event_id text not null,
  action_source text not null,
  test_event_code text,
  status text not null,                -- sent | error | skipped_no_token | skipped_test_contact | skipped_no_match_keys
  http_status int,
  response jsonb,
  match_keys text[]                    -- which user_data keys were sent (names only, never values)
);
create unique index if not exists capi_events_live_once
  on public.capi_events(event_id) where status = 'sent' and test_event_code is null;

